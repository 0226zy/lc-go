// cloneBoard 把字符串形式的棋盘转为 [][]byte，避免用例间相互污染
func cloneBoard(board [][]string) [][]byte {
	out := make([][]byte, len(board))
	for i, row := range board {
		out[i] = make([]byte, len(row))
		for j, cell := range row {
			out[i][j] = cell[0]
		}
	}
	return out
}

// wantBoard 把字符串形式的期望棋盘转为 [][]byte
func wantBoard(board [][]string) [][]byte {
	return cloneBoard(board)
}

// isValidSolution 校验棋盘是一个合法的完整数独：
// 无空格，且每行、每列、每宫的数字均为 1-9 不重复
func isValidSolution(board [][]byte) bool {
	for i := 0; i < 9; i++ {
		var row, col [9]bool
		for j := 0; j < 9; j++ {
			if board[i][j] < '1' || board[i][j] > '9' {
				return false
			}
			d := board[i][j] - '1'
			if row[d] {
				return false
			}
			row[d] = true
			d2 := board[j][i] - '1'
			if col[d2] {
				return false
			}
			col[d2] = true
		}
	}
	for br := 0; br < 3; br++ {
		for bc := 0; bc < 3; bc++ {
			var box [9]bool
			for i := 0; i < 3; i++ {
				for j := 0; j < 3; j++ {
					d := board[br*3+i][bc*3+j] - '1'
					if box[d] {
						return false
					}
					box[d] = true
				}
			}
		}
	}
	return true
}

